"""Приведение слов к словарной форме (лемме) для сравнения текстов, не
совпадающих дословно.

Зачем это нужно: SimHash (core/simhash.py) ловит только почти-дословные
повторы — совпадающие символьные/пословные n-граммы. Одна и та же новость,
пересказанная разными каналами разными словами ("ЦБ повысил ставку" vs
"Центробанк принял решение о повышении ставки"), почти не даёт общих
n-грамм из-за русской словоформы (падежи/спряжения меняют само слово:
"ставку" vs "ставки", "открылась" vs "открытии") — и SimHash тут
принципиально бессилен, что подтверждено экспериментально (см. тесты и
комментарий в paraphrase_deduplicator.py).

Лемматизация (приведение каждого слова к начальной словарной форме через
pymorphy3 — офлайновый морфологический анализатор для русского языка, не
требует сети/API/ML-весов) решает именно эту проблему: "ставку" и "ставки"
после лемматизации становятся одним и тем же токеном "ставка", и пересказы
одной новости начинают давать заметное пересечение множеств лемм, тогда как
у по-настоящему разных новостей пересечение остаётся нулевым или близким к
нулю (эмпирически проверено на реальных примерах при разработке).

MorphAnalyzer из pymorphy3 дорог в создании (загружает словарь), поэтому
создаётся один раз на процесс (модульный синглтон), а не на каждый вызов.
"""

