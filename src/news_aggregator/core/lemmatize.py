# Однобуквенные "слова", оставшиеся после нормализации (обрывки пунктуации,
# отдельные буквы) — почти всегда шум, не несущий смысла для сравнения.
_MIN_TOKEN_LENGTH = 2

_morph: pymorphy3.MorphAnalyzer | None = None


def _get_morph() -> pymorphy3.MorphAnalyzer:
    """Ленивая инициализация MorphAnalyzer — один экземпляр на процесс."""
    global _morph
    if _morph is None:
        _morph = pymorphy3.MorphAnalyzer()
    return _morph


def extract_lemma_set(normalized_text: str) -> frozenset[str]:
    """Возвращает множество лемм значимых слов нормализованного текста.

    Args:
        normalized_text: Текст, уже прошедший
            news_aggregator.core.text_utils.normalize_text (нижний регистр,
            без пунктуации/ссылок/хэштегов).

    Числа и неизвестные слова (не найденные в словаре) возвращаются как есть —
    pymorphy3 в этом случае просто не меняет форму, что для сравнения
    множеств безопасно (совпадающие числа/аббревиатуры всё равно совпадут
    как токены).
    """
    if not normalized_text:
        return frozenset()

    morph = _get_morph()
    lemmas: set[str] = set()
    for word in normalized_text.split():
        if len(word) < _MIN_TOKEN_LENGTH:
            continue
        lemma = morph.parse(word)[0].normal_form
        if lemma in STOPWORDS:
            continue
        lemmas.add(lemma)
    return frozenset(lemmas)


def jaccard_similarity(a: frozenset[str], b: frozenset[str]) -> float:
    """Коэффициент Жаккара двух множеств: |A∩B| / |A∪B|, 0.0 если оба пусты."""
    if not a or not b:
        return 0.0
    union_size = len(a | b)
    if union_size == 0:
        return 0.0
    return len(a & b) / union_size


def stem_set(lemmas: frozenset[str], length: int | None) -> frozenset[str]:
    """Усекает каждую лемму до `length` символов («основа» для нечёткого сравнения).

    Лемматизатор не склеивает родственные слова: «Россия» / «российский» /
    «россиянин», «Канада» / «канадец», «хоккей» / «хоккейный» — у них разные
    леммы. Общий префикс склеивает их в одну основу. Слова вне словаря
    pymorphy оставляет как есть, поэтому «биткоин» и «биткоина» тоже были бы
    разными токенами, пока не усечены. Числа и слова не длиннее `length`
    не трогаются. length=None — без усечения.
    """
    if length is None:
        return lemmas
    return frozenset(t if (t.isdigit() or len(t) <= length) else t[:length] for t in lemmas)


def numbers_in(lemmas: frozenset[str]) -> frozenset[str]:
    """Числовые токены множества лемм (у кандидатов из индекса есть только оно)."""
    return frozenset(t for t in lemmas if t.isdigit())
